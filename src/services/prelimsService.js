/**
 * Generate dynamic test questions based on subject, count & exam type
 */
export function generatePrelimsTest({ examType = 'upsc', subjects = ['General Studies I'], questionCount = 10 }) {
  const bank = PRELIMS_QUESTION_BANK[examType.toLowerCase()] || PRELIMS_QUESTION_BANK.upsc;
  
  // Filter or duplicate to match requested questionCount
  let selected = [...bank];
  
  // If requested count is higher than bank, duplicate with slight variations
  while (selected.length < questionCount) {
    const orig = bank[selected.length % bank.length];
    selected.push({
      ...orig,
      id: `${orig.id}-gen-${selected.length}`,
      questionEn: `[Mock Q.${selected.length + 1}] ${orig.questionEn}`,
      questionHi: `[अभ्यास प्र.${selected.length + 1}] ${orig.questionHi}`
    });
  }

  return selected.slice(0, questionCount);
}
